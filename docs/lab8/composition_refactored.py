"""Рефакторинг ієрархії: Replace Inheritance with Composition (СТАН PASS).

Застосовані техніки:
- Усунення успадкування: видалено (BaseReportExporter), DIT зменшено з 3 до 1.
- Композиція та агрегація: форматер впроваджується через конструктор (DI).
- Кількість Overridden методів = 0 (усунено крихкість базового класу).
"""

from typing import Any, Protocol


class IReportFormatter(Protocol):
    """Абстрактний контракт форматування звітів."""

    def format_header(self, title: str) -> str:
        ...

    def format_body(self, payload: dict[str, Any]) -> str:
        ...

    def format_footer(self) -> str:
        ...


class TextReportFormatter:
    """Текстовий форматер (автономний компонент, DIT=1)."""

    def format_header(self, title: str) -> str:
        return f"=== {title.strip().upper()} ==="

    def format_body(self, payload: dict[str, Any]) -> str:
        lines = [f"{k}: {v}" for k, v in payload.items()]
        return "\n".join(lines)

    def format_footer(self) -> str:
        return "-- End of Text Report --"


class HtmlReportFormatter:
    """HTML-форматер (автономний компонент, DIT=1)."""

    def format_header(self, title: str) -> str:
        return f"<header><h1>{title}</h1></header>"

    def format_body(self, payload: dict[str, Any]) -> str:
        rows = [f"<tr><td>{k}</td><td>{v}</td></tr>" for k, v in payload.items()]
        return f"<table class='report-table'>{''.join(rows)}</table>"

    def format_footer(self) -> str:
        return "<footer>Generated by RunTracker Composition Engine</footer>"


class AdvancedRunnerDashboard:
    """Оптимізований дашборд бігуна.
    
    Метрики Лоренца-Кіда (СТАН PASS):
    - DIT = 1 (прямий нащадок object, жодного спадкового дерева)
    - Overridden Methods = 0 (немає перезапису методів предків)
    - Делегування через інтерфейс IReportFormatter (Loose Coupling)
    """

    def __init__(self, formatter: IReportFormatter):
        # Впровадження залежності замість жорсткого наслідування (Composition)
        self._formatter = formatter

    def build_dashboard(self, runner_name: str, stats: dict[str, Any]) -> str:
        header = self._formatter.format_header(f"Runner: {runner_name}")
        body = self._formatter.format_body(stats)
        widget = "<div class='widget'>HR Zones & Pace Summary</div>"
        footer = self._formatter.format_footer()

        return f"<div class='dashboard-wrapper'>\n{header}\n{body}\n{widget}\n{footer}\n</div>"
