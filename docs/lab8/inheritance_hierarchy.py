"""Модуль дослідження антипатерну Inheritance Hell (ієрархія з крихким наслідуванням).

Метрики Лоренца-Кіда:
- DIT = 3 (Глибина дерева наслідування: Base -> Html -> Dashboard)
- PIM (Public Interface Size) > 20 успадкованих та публічних методів
- Overridden Methods: масове затирання методів предка
"""

from typing import Any


class BaseReportExporter:
    """Рівень 1: Базовий експортер звітів."""

    def format_title(self, raw_title: str) -> str:
        return f"=== {raw_title.strip().upper()} ==="

    # ЗМІНА ДЛЯ КРАШ-ТЕСТУ: додано обов'язковий аргумент 'context'
    def render_header(self, title: str, context: dict[str, Any]) -> str:
        meta = context.get("env", "production")
        return f"HEADER: {self.format_title(title)} [Env: {meta}]"

    def render_body(self, payload: dict[str, Any]) -> str:
        lines = [f"{k}: {v}" for k, v in payload.items()]
        return "\n".join(lines)

    def render_footer(self) -> str:
        return "-- End of Report --"

    def build_export(self, title: str, payload: dict[str, Any]) -> str:
        # Спадковий виклик
        h = self.render_header(title, {"env": "prod"})
        b = self.render_body(payload)
        f = self.render_footer()
        return f"{h}\n{b}\n{f}"


class HtmlReportExporter(BaseReportExporter):
    """Рівень 2 (DIT = 2): HTML-спеціалізація. Перевизначає методи предка."""

    # Дочірній клас НЕ ЗНАЄ про новий обов'язковий аргумент context у предку!
    def render_header(self, title: str) -> str:
        # Виклик super() зламається, бо предок тепер вимагає context!
        return f"<h1>{super().render_header(title)}</h1>"

    def render_body(self, payload: dict[str, Any]) -> str:
        rows = [f"<tr><td>{k}</td><td>{v}</td></tr>" for k, v in payload.items()]
        return f"<table>{''.join(rows)}</table>"

    def render_footer(self) -> str:
        return "<footer>Generated by RunTracker HTML Engine</footer>"


class AdvancedRunnerDashboardExporter(HtmlReportExporter):
    """Рівень 3 (DIT = 3): Каскадний нащадок. Крихкість ієрархії сягає максимуму."""

    def render_header(self, title: str) -> str:
        # Подвійний каскадний виклик через super()
        return f"<div class='dashboard-header'>{super().render_header(title)}</div>"

    def render_body(self, payload: dict[str, Any]) -> str:
        base_table = super().render_body(payload)
        widget = "<div class='widget'>HR Zones & Pace Summary</div>"
        return f"{base_table}\n{widget}"

    def render_footer(self) -> str:
        return "<footer class='dashboard-footer'>Enterprise RunTracker v8</footer>"

    def build_dashboard(self, runner_name: str, stats: dict[str, Any]) -> str:
        # Виклик методу, який каскадно падає через несумісність сигнатур
        return self.render_header(f"Runner: {runner_name}")
