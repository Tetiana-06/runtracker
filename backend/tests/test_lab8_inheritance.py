from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import pytest
from docs.lab8.composition_refactored import (
    AdvancedRunnerDashboard,
    HtmlReportFormatter,
    TextReportFormatter,
)
from docs.lab8.inheritance_hierarchy import (
    AdvancedRunnerDashboardExporter,
    BaseReportExporter,
    HtmlReportExporter,
)


def test_base_report_exporter_direct():
    """Прямий виклик базового експортера з новим аргументом context."""
    exporter = BaseReportExporter()
    out = exporter.build_export("Weekly Digest", {"km": 42.0})
    assert "WEEKLY DIGEST" in out
    assert "km: 42.0" in out


def test_inheritance_fragility_crash_fail():
    """FAIL: точкова зміна в BaseReportExporter ламає весь ланцюжок нащадків."""
    dashboard = AdvancedRunnerDashboardExporter()

    # Спроба виклику призводить до TypeError через невідповідність аргументів у ланцюжку super()
    with pytest.raises(TypeError) as exc_info:
        dashboard.build_dashboard("Олександр", {"distance": 21.1})

    assert "missing 1 required positional argument: 'context'" in str(exc_info.value)


def test_composition_refactored_dashboard_pass():
    """PASS: рефакторинг через композицію (DIT=1, Overridden=0) повністю усуває крихкість."""
    # 1. Використання з HTML-форматером
    html_dashboard = AdvancedRunnerDashboard(HtmlReportFormatter())
    html_out = html_dashboard.build_dashboard("Марія", {"distance_km": 15.0, "avg_hr": 142})
    assert "<header><h1>Runner: Марія</h1></header>" in html_out
    assert "HR Zones & Pace Summary" in html_out
    assert "Generated by RunTracker Composition Engine" in html_out

    # 2. Легка заміна на текстовий форматер без зміни коду дашборду
    text_dashboard = AdvancedRunnerDashboard(TextReportFormatter())
    text_out = text_dashboard.build_dashboard("Іван", {"distance_km": 5.0})
    assert "=== RUNNER: ІВАН ===" in text_out
    assert "-- End of Text Report --" in text_out
